/** Arabic plural picker: 1 → one, 2 → two, 3–10 → `N few`, 11+ → `N many`. */
function arPlural(count: number, one: string, two: string, few: string, many: string): string {
  if (count === 1) return one;
  if (count === 2) return two;
  if (count >= 3 && count <= 10) return `${count} ${few}`;
  return `${count} ${many}`;
}

