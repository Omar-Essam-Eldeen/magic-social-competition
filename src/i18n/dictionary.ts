// bodies, names, usernames) is NEVER translated — only these UI strings are.
// Brand name "Magic Social" stays untranslated everywhere.
// Relative times ("2h ago") are NOT in here: they come from date-fns, so the
// page agents must pass `locale: lang === "ar" ? ar : enUS` to
// formatDistanceToNow in PostCard, CommentItem and Notifications.

